#!/usr/bin/env python3
"""Copies the icons named in mdi-icons.txt from an @mdi/svg package into
data/icons/mdi and regenerates data/resources/mdi.gresource.xml.

Usage: update-mdi-icons.py PATH_TO_MDI_SVG_PACKAGE

The package comes from `npm pack @mdi/svg`; PATH points at its extracted
`package` directory.
"""
import pathlib
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIST = ROOT / "build-aux" / "mdi-icons.txt"
OUT = ROOT / "data" / "icons" / "mdi"
XML = ROOT / "data" / "resources" / "mdi.gresource.xml"


def main() -> None:
    package = pathlib.Path(sys.argv[1])
    names = [
        line.strip()
        for line in LIST.read_text().splitlines()
        if line.strip() and not line.startswith("#")
    ]
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    shutil.copy(package / "LICENSE", OUT / "LICENSE")

    entries = []
    for name in sorted(set(names)):
        source = package / "svg" / f"{name}.svg"
        # GTK recolors icons whose names end in -symbolic to the text color.
        target = OUT / f"mdi-{name}-symbolic.svg"
        shutil.copy(source, target)
        entries.append(
            f'    <file compressed="true" preprocess="xml-stripblanks" '
            f'alias="icons/scalable/actions/{target.name}">'
            f"../icons/mdi/{target.name}</file>"
        )

    XML.write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- Generated by build-aux/update-mdi-icons.py -->\n"
        "<gresources>\n"
        '  <gresource prefix="/net/dunevent/Sanctum/">\n'
        + "\n".join(entries)
        + "\n  </gresource>\n</gresources>\n"
    )
    print(f"{len(entries)} icons")


if __name__ == "__main__":
    main()
